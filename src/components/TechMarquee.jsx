function MarqueeTrack({ items, speed = 40 }) {
  const reduced = useReducedMotion();
  const totalWidth = items.length * 200; // approximate width per item with logo

  return (
    <div className="relative flex overflow-hidden py-2">
      {/* Gradient masks on edges for smooth fade */}
      <div className="pointer-events-none absolute inset-y-0 left-0 z-10 w-20 bg-gradient-to-r from-base to-transparent sm:w-32" />
      <div className="pointer-events-none absolute inset-y-0 right-0 z-10 w-20 bg-gradient-to-l from-base to-transparent sm:w-32" />

      <motion.div
        className="flex gap-5"
        animate={reduced ? {} : { x: [0, -totalWidth] }}
        transition={
          reduced
            ? {}
            : {
                x: {
                  repeat: Infinity,
                  repeatType: 'loop',
                  duration: speed,
                  ease: 'linear',
                },
              }
        }
      >
        {/* Double the items for seamless loop */}
        {[...items, ...items].map((tech, i) => (
          <span
            key={`${tech.name}-${i}`}
            className="glass-card flex shrink-0 items-center gap-3 rounded-full border border-white/[0.08] bg-white/[0.04] px-5 py-2.5 backdrop-blur transition-all duration-300 hover:border-accent-violet/40 hover:shadow-glow group"
          >
            <span className="flex shrink-0 items-center justify-center transition-transform duration-300 group-hover:scale-110">
              {tech.icon}
            </span>
            <span className="whitespace-nowrap font-display text-sm font-medium text-ink">
              {tech.name}
            </span>
          </span>
        ))}
      </motion.div>
    </div>
  );
}

export default function TechMarquee() {
  return (
    <section className="relative overflow-hidden py-12" aria-label="Technology stack">
      <div className="container-x relative">
        <Reveal>
          <div className="mb-6 text-center">
            <span className="font-mono text-xs uppercase tracking-[0.3em] text-accent-cyan/90">
              Toolbox
            </span>
            <h2 className="mt-2 font-display text-2xl font-bold text-ink sm:text-3xl">
              Technologies I work with <span className="text-gradient">.</span>
            </h2>
          </div>
        </Reveal>
        <MarqueeTrack items={TECH_ITEMS} />
      </div>
    </section>
  );
}
